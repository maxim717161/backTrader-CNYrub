"""Гипотеза о трендовости: движение, начавшееся в одну сторону, продолжается дольше, чем
стоят издержки.

Запуск: `PYTHONPATH=. python -m research.trend` — пересчитывает всё и пишет
`research/REPORT_trend.md` и `research/out/grid_trend.csv`.

Что должно быть верно, если гипотеза права (и что мы проверяем):
1. автокорреляция доходностей положительна, VR > 1, Хёрст > 0,5 — хотя бы на каком-то масштабе;
2. после пробоя канала цена в среднем идёт дальше пробоя на величину больше круга (12 ₽);
3. правила следования за движением (пробой, z-score, импульс, продолжение разрыва, первый час)
   зарабатывают после издержек и на обучении, и на проверке, и устойчиво по годам.
"""

from __future__ import annotations

import itertools

from research import battery, core, evaluate, report
from research.families import Spec

MIN_STOP_TICKS = 8

FOCUS = (
    "Для гипотезы о тренде нужны положительная автокорреляция, VR > 1 и Хёрст > 0,5 хотя бы "
    "на одном масштабе. Любое значение ниже нейтрального — свидетельство против."
)

INTRO = (
    "Ту же сетку правил, что у живой стратегии (пробой канала со стопом по размаху), мы расширяем "
    "остальными способами следовать за движением: пробой z-score, импульс за окно, продолжение "
    "ночного разрыва, продолжение первого часа, продолжение последнего движения на 1–5 минут. "
    "Версии «ночь» не закрываются в конце дня и держатся до стопа или конца контракта."
)


def specs() -> list[Spec]:
    out: list[Spec] = []
    for channel, stop, flatten in itertools.product((15, 30, 60, 120, 240, 525), (2, 4, 8), (True, False)):
        out.append(Spec("donchian", 1, dict(channel=channel, stop=stop, min_stop=MIN_STOP_TICKS * core.UNIT), flatten))
    for window, k, stop, flatten in itertools.product((60, 240), (2, 3), (4, 8), (True, False)):
        out.append(Spec("zscore", 1, dict(window=window, k=k, stop=stop, min_stop=MIN_STOP_TICKS * core.UNIT), flatten))
    for lookback, hold in itertools.product((30, 60, 120, 240), (30, 60, 120)):
        out.append(Spec("momentum", 1, dict(lookback=lookback, every=hold, hold=hold, min_move=10)))
    for gap, hold in itertools.product((5, 10, 20), (0, 60)):
        out.append(Spec("gap", 1, dict(min_gap=gap, hold=hold)))
    for window, move in itertools.product((30, 60, 120), (0, 10)):
        out.append(Spec("firsthour", 1, dict(window=window, min_move=move)))
    for move, hold in itertools.product((3, 5), (1, 3, 5)):
        out.append(Spec("scalp", 1, dict(min_move=move, hold=hold)))
    return out


CONCLUSIONS = """**Вердикт: гипотеза о трендовости не подтверждена. Данные ближе к «случайному блужданию с шумом», а на коротких масштабах — к возврату.**

### Что говорит описательная часть

1. **Внутри дня тренда нет.** Автокорреляция соседних окон отрицательна на всех масштабах до часа (15 мин: −0,088, интервал [−0,125; −0,055]); положительной она становится только на 120 минутах (+0,042), и интервал включает ноль. Хёрст 0,45 < 0,5. Доля соседних движений в одну сторону 44–49% при ожидаемых 50%.
2. **Большая часть «возврата» — шум последней сделки, но не вся.** Сырой VR 0,64–0,86 после вычитания шума поднимается до 0,82–0,97, оставаясь ниже 1 (VR 120 мин: 0,816, интервал [0,752; 0,904]).
3. **Этот остаток неоднороден.** По годам: 2022 — VR 0,76 и Хёрст 0,40, а 2023–2026 — VR 0,92–1,02 и Хёрст 0,49–0,52, то есть блуждание. В оживлённые дни (оборот выше медианы) VR 0,99 [0,96; 1,02], в тонкие — 0,78. Следовательно, сопротивление тренду — свойство тонких торгов и 2022 года, а не устойчивое свойство инструмента.
4. **На дневном масштабе памяти нет.** Автокорреляция дневных доходностей ≈ 0 на всех лагах 1–5, VR дневной ≈ 1 (интервалы широкие: контрактов всего 19, так что слабый тренд на неделях этими данными не исключить и не обнаружить).
5. **Ночной разрыв закрывается, а не продолжается:** наклон хода первого часа на разрыв −0,37 [−0,53; −0,20].
6. **Событийное исследование пробоев.** Сразу после пробоя (5–15 мин) цена в среднем откатывается (−0,4 ₽). За 1–4 часа средний ход в сторону пробоя положителен (+0,4…+2,5 ₽, t до 2,3), но это в 5–30 раз меньше круга в 12 ₽.

### Что говорит торговая часть

- 82 варианта в 6 семействах: пробой канала (36), пробой z-score (16), импульс (12), продолжение разрыва (6), продолжение первого часа (6), продолжение последнего движения (6).
- Ни один вариант не значим на всём периоде (максимум t = 1,6) и на обучении (максимум 0,9), и ни один на проверке. Проверка перебора (White): p = 0,98 на обучении и 0,78 на всём периоде — лучший вариант неотличим от лучшего случайного из 82.
- Импульс, продолжение разрыва, продолжение первого часа и продолжение последнего движения **убыточны во всех вариантах**, причём ещё до издержек они около нуля (gross −3…+5 ₽ при круге 12 ₽): издержки убивают их полностью. Последнее движение на 1–5 минут — самое показательное: gross = 0, net = −12 ₽, ровно круг.
- Пробои с закрытием в конце дня тоже убыточны (net в среднем −7 ₽): gross +5 ₽ не покрывает 12 ₽.
- Единственное, что выглядит как слабый сигнал: пробой канала или z-score **без закрытия в конце дня**, со стопом 4–8 размахов, держится до стопа или конца контракта. Net +12…+35 ₽ за сделку (gross +25…+47 ₽), положителен на обучении и на проверке, в каждом из пяти лет у лучшего варианта (`donchian[+](channel=60, stop=4, ночь)` — +31, +11, +17, +14, +92 ₽). Но у него доля плюсовых сделок 5–7%: прибыль рождают единичные длинные движения, поэтому t = 0,5–1,6 и незначим ни один из 26 вариантов с удержанием через ночь. Покупки у лучшего варианта дают +13 ₽, продажи +33 ₽ (оба незначимы), а зеркало (то же правило с обратным знаком) даёт −8 ₽ — не зеркальный убыток размера прибыли, но и не плюс.
- Мощность: у лучшего варианта стандартная ошибка средней сделки ≈ 15 ₽ при прибыли 23 ₽ на ≈ 400 сделок. Чтобы подтвердить такую прибыль с t = 3, нужно порядка 1500 сделок, то есть около 15 лет при нынешней частоте. Имеющихся 4,4 лет для этого недостаточно ни в какую сторону.

### Что из этого следует для стратегии

1. Минутный тренд-следящий вход с закрытием в конце дня (то, что делают `thirty/fortyfive/sixty` с закрытием дня) на этих данных **не имеет преимущества перед издержками**: gross около нуля, а круг стоит 12 ₽.
2. Если и искать тренд, то на удержании через ночь с широким стопом и малой долей прибыльных сделок. Это единственное направление с положительными оценками на обеих половинах выборки, но с недоказанной значимостью и с гэп-риском позиции на ночь/выходные.
3. Гипотеза «инструмент трендовый» не нужна для объяснения результатов, а часть данных (возврат в тонкие периоды, закрытие разрывов) говорит скорее против неё: соответствующая проверка — в ветке с гипотезой о контртрендовости.

### Оговорки

- Результаты зависят от допущения «вход по закрытию следующей минуты»; на реальной бирже входы по рынку хуже на спред, а у правил с лимитным входом — лучше, но этого по минуткам проверить нельзя.
- Круг 12 ₽ принят с проскальзыванием в 1 тик на сторону. Без проскальзывания (круг 10 ₽) у лучшего варианта t = 1,7, даже при нулевых издержках — 2,2, что для лучшего из 82 уже не значимо (поправка White на перебор).
- Выходные исключены (торги разрежены); позиции «на ночь» проходят через выходные только по ценам понедельника.
- Сетка в 82 варианта — это уже перебор; все t без поправки завышают значимость, поправка White приведена выше.
- 19 контрактов — мало независимых недельных наблюдений: дневной и недельный масштаб статистически почти не проверяется.
"""


def main() -> None:
    market = core.load_front()
    data = core.arrays(market)
    described = battery.run_all(market)
    plan = specs()
    result = evaluate.run_grid(plan, market, data, verbose=True)
    chosen = evaluate.selection(result)
    by_label = {spec.label(): spec for spec in plan}
    text = "\n".join(
        [
            "# Гипотеза: инструмент трендовый\n",
            report.method_section(),
            report.battery_section(described, FOCUS),
            report.grid_section("2. Зарабатывают ли правила следования за движением", INTRO, result, plan, chosen),
            report.detail_section(by_label[chosen["best_in_sample"]], evaluate.detail(by_label[chosen["best_in_sample"]], market, data)),
            "## 3. Выводы\n\n" + CONCLUSIONS,
        ]
    )
    report.save("trend", text, result)


if __name__ == "__main__":
    main()
