"""Гипотеза о контртрендовости: после рывка цена возвращается, и на возврате можно заработать
после издержек.

Запуск: `PYTHONPATH=. python -m research.countertrend` — пересчитывает всё и пишет
`research/REPORT_countertrend.md` и `research/out/grid_countertrend.csv`.

Что должно быть верно, если гипотеза права (и что мы проверяем):
1. автокорреляция доходностей отрицательна, VR < 1, Хёрст < 0,5 — и не только как шум
   последней сделки, который невозможно заработать рыночными заявками;
2. после пробоя канала цена в среднем возвращается внутрь канала на величину больше круга (12 ₽);
3. правила игры против движения (пробой наоборот, возврат к средней, закрытие разрыва, ставка
   против первого часа, против последнего движения) зарабатывают после издержек и на обучении,
   и на проверке, и устойчиво по годам.
"""

from __future__ import annotations

import itertools

import pandas as pd

from research import battery, core, evaluate, report
from research.families import Spec, build

MIN_DISTANCE_TICKS = (15, 30)


def min_distances() -> tuple[float, ...]:
    return tuple(ticks * core.UNIT for ticks in MIN_DISTANCE_TICKS)

FOCUS = (
    "Для гипотезы о возврате нужны отрицательная автокорреляция, VR < 1 и Хёрст < 0,5 — причём "
    "после вычета шума последней сделки (иначе возврат нельзя заработать) и устойчиво по годам и "
    "режимам рынка."
)

INTRO = (
    "Те же сигналы, что в ветке о тренде, но сделка идёт против них, а выход — по цели возврата "
    "и стопу (кратные размаху минутки за предыдущий час, но не меньше 15 или 30 ₽ — чтобы цель "
    "была выше круга в 12 ₽) и по ограничению времени. Семейства: пробой канала наоборот, возврат "
    "от z-score, закрытие ночного разрыва, ставка против первого часа, ставка против последнего "
    "минутного движения и против импульса за окно."
)


def specs() -> list[Spec]:
    out: list[Spec] = []
    for channel, stop, target, floor, hold in itertools.product((30, 60, 120, 525), (4, 8), (2, 4, 8), min_distances(), (60, 240)):
        out.append(Spec("donchian", -1, dict(channel=channel, stop=stop, target=target, hold=hold, min_stop=floor)))
    for window, k, stop, target, floor in itertools.product((60, 240), (2, 3), (4, 8), (2, 4, 8), min_distances()):
        out.append(Spec("zscore", -1, dict(window=window, k=k, stop=stop, target=target, hold=120, min_stop=floor)))
    for lookback, hold in itertools.product((30, 60, 120, 240), (30, 60, 120)):
        out.append(Spec("momentum", -1, dict(lookback=lookback, every=hold, hold=hold, min_move=10)))
    for gap, hold in itertools.product((5, 10, 20), (0, 60)):
        out.append(Spec("gap", -1, dict(min_gap=gap, hold=hold)))
    for window, move in itertools.product((30, 60, 120), (0, 10)):
        out.append(Spec("firsthour", -1, dict(window=window, min_move=move)))
    for move, hold in itertools.product((3, 5), (1, 3, 5)):
        out.append(Spec("scalp", -1, dict(min_move=move, hold=hold)))
    return out


def bounce_table(market: core.Market, data: dict) -> pd.DataFrame:
    """Можно ли заработать на отрицательной автокорреляции минуток: ставка против последнего движения
    при разной задержке входа. delay=0 — вход по цене самого сигнала, на практике недостижим."""
    rows = []
    for move, hold in itertools.product((3, 5, 10), (1, 5)):
        entries = build(Spec("scalp", -1, dict(min_move=move, hold=hold)), market, data)
        row = {"движение, тиков": move, "удержание, мин": hold}
        for delay in (0, 1, 2):
            stats = core.trade_stats(core.run_entries(data, entries, delay=delay))
            row[f"gross, задержка {delay} мин"] = stats["gross"]
        row["сделок (задержка 1)"] = core.trade_stats(core.run_entries(data, entries, delay=1))["n"]
        rows.append(row)
    return pd.DataFrame(rows).set_index("движение, тиков")


def bounce_section(table: pd.DataFrame) -> str:
    return f"""### Можно ли поймать минутный возврат

Автокорреляция соседних минут отрицательна (−0,14), но заработать на ней можно, только если успеть: ставка против последнего движения, gross на сделку (₽ на контракт; круг стоит {core.round_trip_cost():.0f} ₽).

{report.md(table, 2)}
"""


def gap_table(market: core.Market, data: dict) -> tuple[pd.DataFrame, pd.DataFrame]:
    """Закрытие ночного разрыва: ставка против разрыва до конца дня при росте порога, отдельно по
    направлению разрыва (gross, ₽ на контракт), и по годам для порога в 20 тиков."""
    rows = []
    trades_20 = None
    for threshold in (5, 10, 20, 30, 50):
        trades = core.run_entries(data, build(Spec("gap", -1, dict(min_gap=threshold, hold=0)), market, data))
        if threshold == 20:
            trades_20 = trades
        row = {"разрыв не меньше, тиков": threshold}
        for name, part in (("все", trades), ("вверх (продаём)", trades[trades["side"] == -1]), ("вниз (покупаем)", trades[trades["side"] == 1])):
            mean, _, t, n = core.cluster_mean(part["gross"].to_numpy(), part["day"].to_numpy())
            row[f"{name}: сделок"] = n
            row[f"{name}: gross"] = mean
            row[f"{name}: t"] = t
        rows.append(row)
    years = []
    for year, part in trades_20.groupby(pd.to_datetime(trades_20["day"]).dt.year):
        years.append({"год": year, "сделок": len(part), "gross": part["gross"].mean(), "net": part["net"].mean()})
    return (
        pd.DataFrame(rows).set_index("разрыв не меньше, тиков"),
        pd.DataFrame(years, columns=["год", "сделок", "gross", "net"]).set_index("год"),
    )


def gap_section(table: pd.DataFrame, years: pd.DataFrame) -> str:
    return f"""### Закрытие ночного разрыва: зависимость от размера и направления

Ставка против разрыва по закрытию второй минуты дня, выход в конце дня. Это ретроспективный разрез, выбранный после того, как стало видно, что семейство разрывов лучшее в сетке, поэтому t здесь надо читать осторожно.

{report.md(table, 1)}

Для порога 20 тиков по годам (gross и net — ₽ на сделку):

{report.md(years, 1)}
"""


CONCLUSIONS = """**Вердикт: контртрендовость есть как свойство минутного шума и тонких периодов, но заработать на ней после издержек нельзя; единственный кандидат — закрытие ночных разрывов вверх, и он пока не доказан.**

### Что говорит описательная часть

1. **Отрицательная автокорреляция реальна и сильна на коротких масштабах**: лаг 1 на минутках −0,137 [−0,159; −0,112], на 5 минутах −0,117, на 15 минутах −0,088 [−0,125; −0,055], на 30 минутах −0,047, дальше затухает и на часе уже неотличима от нуля. На лагах 2–3 она в разы слабее (−0,03…0) — это признак шума последней сделки, а не возврата в «истинной» цене.
2. **Шум последней сделки объясняет большую часть**: сырой VR 0,64–0,86, после его вычитания 0,82–0,97, но остаток ниже 1 значимо (30–120 минут: 0,82–0,86; интервалы ниже 1). Хёрст 0,45.
3. **Остаток живёт в 2022 году и в тонкие дни.** 2022: VR 0,76, Хёрст 0,40; 2023–2026: VR 0,92–1,02, Хёрст 0,49–0,52. Дни с оборотом ниже медианы: VR 0,78; выше медианы: 0,99 [0,96; 1,02]. Для рабочих размеров позиции это важно: вход именно в тонкие периоды — это вход по неустойчивой цене.
4. **На дневном масштабе возврата нет** (автокорреляция ≈ 0, VR ≈ 1 до 10 дней, 0,77 на 20 днях с очень широким интервалом [0,48; 1,06]).
5. **Ночной разрыв частично закрывается за первый час**: наклон −0,37 [−0,53; −0,20]; остаток дня — неопределённо (−0,07 [−0,49; +0,27]).
6. **После пробоя канала цена откатывается только на минутах** (5 минут: −0,4 ₽ на контракт, t до −5,9); на горизонте часа и дальше ход в сторону пробоя положителен (+0,4…+2,5 ₽). То есть откат слишком мал и слишком короток, чтобы покрыть 12 ₽.

### Что говорит торговая часть

- 174 варианта в 6 семействах: пробой канала наоборот (96), возврат от z-score (48), против импульса (12), закрытие разрыва (6), против первого часа (6), против последнего минутного движения (6). Цели и стопы — не меньше 15 или 30 ₽, чтобы цель была выше круга в 12 ₽.
- После издержек в плюсе всего **2 из 174**; до издержек в плюсе 59 (в основном нули). Значимых на обучении и на проверке — ни одного. Проверка перебора (White): p = 0,93 на обучении и 0,80 на всём периоде.
- **Минутный возврат поймать нельзя.** Ставка против последнего движения: при входе по цене самого сигнала (недостижимо) gross всего +0,6…+2,2 ₽ на сделку, при входе через минуту — 0,0…+0,5 ₽, при 12 ₽ издержек. Возврат на соседних минутах уже случился к моменту, когда заявку можно исполнить.
- Игра против пробоя и против z-score даёт gross в среднем ≈ 0 (медиана −0,2 ₽), то есть теряет ровно издержки. Игра против импульса и против первого часа даёт отрицательный gross (−1,0 и −4,5 ₽): первый час скорее слабо продолжается (см. ветку про тренд), чем возвращается.
- **Закрытие ночного разрыва — единственное семейство с положительным gross.** Сильная зависимость от размера разрыва (разрыв ≥5 тиков: +1,9 ₽; ≥10: +16,4; ≥20: +30,0; ≥50: +51,2) и от направления: ставка против **разрыва вверх** даёт gross +24 … +127 ₽ (t 2,1…2,8 при порогах 10–50 тиков), против разрыва вниз — около нуля (t −0,3…0,5). Для порога 20 тиков net +18 ₽ на сделку (134 сделок), положителен в каждом из пяти лет (+25, +11, +10, +23, +28 ₽), зеркальное правило (идти за разрывом) даёт −42 ₽, t = −2,8.
- Но: (а) это лучшее из 174 вариантов, а ретроспективный разрез по порогу и направлению — ещё и повод для самообмана; поправка White для всей сетки 0,80; (б) сделок мало: 134 за 4,4 года, из них разрывов вверх 66; (в) разрыв считается от последней цены предыдущего дня до первой сделки, а ночью торги идут с тонким стаканом — реальные входы по второй минуте дня могут исполняться хуже, чем по минутному закрытию; (г) направленность «вверх» (ослабление рубля ночью с последующим откатом) может быть свойством этих лет, а не инструмента.
- Мощность: для порога 20 тиков при сделках по 30 в год t = 1,2 по net; чтобы подтвердить +18 ₽ с t = 3, нужно порядка 840 сделок — десятилетия. Только разрывы вверх: net +39 ₽ при 66 сделках, t по net 2,1; для t = 3 нужно около 130 таких сделок (≈ 9 лет).

### Что из этого следует для стратегии

1. Минутная контртрендовая стратегия (скальпинг на откате) на этих данных невозможна: edge в 0–2 ₽ против 12 ₽ издержек. Лимитные заявки внутри спреда могли бы забрать часть возврата, но по минуткам это проверить нельзя — нужны сделки или стакан.
2. Единственное, что стоит накапливать данные и проверять дальше, — закрытие ночных разрывов вверх (по возможности на других контрактах и валютных парах, где история длиннее). Торговать это сейчас рано: 66 сделок.
3. Гипотеза «инструмент контртрендовый» в общем виде не подтверждена: возврат есть на минутах (шум) и в тонкие периоды, но не на масштабах, где его можно заработать, и не в 2023–2026 в оживлённые дни.

### Оговорки

- Результаты зависят от допущения «вход по закрытию следующей минуты». С исполнением быстрее минуты (по рынку внутри минуты) цифры скальпинга лучше (колонка «задержка 0»), но всё равно ниже издержек.
- Круг 12 ₽ принят с проскальзыванием в 1 тик на сторону; даже при 10 ₽ ни один вариант не становится значимым (лучший — разрыв ≥20 тиков: net около +20 ₽, t ≈ 1,3).
- Выходные исключены (торги разрежены); разрыв после выходных — это разрыв пятница → понедельник.
- Сетка в 174 варианта — это перебор; все t без поправки завышают значимость, поправка White приведена выше.
- 19 контрактов — мало независимых недельных наблюдений.
"""


def main() -> None:
    market = core.load_front()
    data = core.arrays(market)
    described = battery.run_all(market)
    plan = specs()
    result = evaluate.run_grid(plan, market, data, verbose=True)
    chosen = evaluate.selection(result)
    by_label = {spec.label(): spec for spec in plan}
    best = by_label[chosen["best_in_sample"]]
    text = "\n".join(
        [
            "# Гипотеза: инструмент контртрендовый\n",
            report.method_section(),
            report.battery_section(described, FOCUS),
            report.grid_section("2. Зарабатывают ли правила игры против движения", INTRO, result, plan, chosen),
            report.detail_section(best, evaluate.detail(best, market, data)),
            bounce_section(bounce_table(market, data)),
            gap_section(*gap_table(market, data)),
            "## 3. Выводы\n\n" + CONCLUSIONS,
        ]
    )
    report.save("countertrend", text, result)


if __name__ == "__main__":
    main()
